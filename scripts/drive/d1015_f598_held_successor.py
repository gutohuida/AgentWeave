"""Acceptance drive for F598: with auto-continue off, a checkpoint successor waits for Continue.

Before the fix, the successor entry a cutover queues was delivered by the next project-wide
redrain (any run's end, or a settings save), so automatic checkpoints chained into unattended
paid turns. This drive takes one real Haiku turn past a low token threshold, lets the Hub
checkpoint and cut over, then saves the settings unchanged (a redrain door) and checks that no
turn started. Only then does it press Continue, and that turn must start.

Run against a scratch Hub that `e2e.py hub-up` started, after `e2e.py setup` and
`e2e.py agent <project> alpha - claude haiku`:

  py -3.11 scripts/drive/d1015_f598_held_successor.py <project-id> [agent]

Exit status 1 when any check fails. Costs two to three Haiku turns plus one checkpoint worker call.
"""

import importlib.util
import pathlib
import sys
import time

_E2E = pathlib.Path(__file__).resolve().parents[2] / ".claude" / "skills" / "e2e-loop" / "e2e.py"
_spec = importlib.util.spec_from_file_location("e2e", _E2E)
e2e = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(e2e)

failures = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail else ""))
    if not ok:
        failures.append(name)


def alpha_runs(project, agent):
    return e2e.ro().execute(
        "select id, status, started_at, conversation_id from runs "
        "where project_id=? and agent=? order by started_at",
        (project, agent),
    ).fetchall()


def checkpoint_entry(project, agent, after=0, entry_id=None):
    """The first checkpoint entry queued after sequence *after*, or the one named *entry_id*.

    Tracked by id: a successor turn can cross the threshold again and queue a newer entry, and a
    reused project holds entries from earlier drives."""
    if entry_id is not None:
        return e2e.ro().execute(
            "select id, sequence, state, delivered_in_run_id, conversation_id "
            "from inbound_queue_entries where id=?",
            (entry_id,),
        ).fetchone()
    return e2e.ro().execute(
        "select id, sequence, state, delivered_in_run_id, conversation_id "
        "from inbound_queue_entries where project_id=? and agent=? and origin_type='checkpoint' "
        "and sequence>? order by sequence limit 1",
        (project, agent, after),
    ).fetchone()


def save_settings(project, **changes):
    settings = e2e.call("GET", f"/projects/{project}/settings")
    settings.update(changes)
    return e2e.request("PUT", f"/projects/{project}/settings", settings)


def main(project, agent="alpha"):
    runner = next(
        r for r in e2e.call("GET", f"/projects/{project}/runners") if r["cli"] == "claude"
    )
    status, saved = save_settings(
        project,
        checkpoint_mode="automatic",
        checkpoint_threshold_mode="tokens",
        checkpoint_threshold_value=5000,
        checkpoint_runner_id=runner["id"],
        checkpoint_auto_continue=False,
    )
    check("settings accepted", status == 200, str(status))

    after = e2e.ro().execute(
        "select coalesce(max(sequence), 0) as s from inbound_queue_entries"
    ).fetchone()["s"]
    run_id = e2e.cmd_turn(
        project, agent, "Read README.md and reply with its first line, nothing else.", fresh=True
    )
    check("first turn started", run_id is not None)
    if run_id is None:
        return
    e2e.wait_for(run_id, 5)

    # The checkpoint is generated by a worker after the reading; give it time to cut over.
    entry = None
    deadline = time.time() + 180
    while time.time() < deadline:
        entry = checkpoint_entry(project, agent, after)
        if entry is not None:
            break
        time.sleep(5)
    check("a cutover queued the successor's checkpoint entry", entry is not None)
    if entry is None:
        return
    successor, mine = entry["conversation_id"], entry["id"]

    # F604: the checkpoint is written from the finished turn, not from its first mid-turn reading.
    # A worker row is written after its call, so its start is created_at - duration_ms.
    timing = e2e.ro().execute(
        "select (julianday(w.created_at) - julianday(r.ended_at)) * 86400.0 "
        "- w.duration_ms / 1000.0 as lead from worker_invocations w join runs r "
        "on r.conversation_id = w.conversation_id where r.id=? and w.kind='checkpoint'",
        (run_id,),
    ).fetchone()
    check(
        "the checkpoint was generated after its turn ended (F604)",
        timing is not None and timing["lead"] >= 0,
        f"started {timing['lead']:+.2f}s after the turn ended" if timing else "no worker row",
    )
    time.sleep(10)
    entry = checkpoint_entry(project, agent, entry_id=mine)
    check(
        "the run-end redrain did not deliver it",
        entry["state"] == "queued",
        f"state={entry['state']} run={entry['delivered_in_run_id']}",
    )

    # A settings save re-drains every queued agent in the project (`projects.py`): the F598 door.
    before = len(alpha_runs(project, agent))
    status, _ = save_settings(project)
    check("an unchanged settings save is accepted", status == 200, str(status))
    time.sleep(20)
    after = alpha_runs(project, agent)
    entry = checkpoint_entry(project, agent, entry_id=mine)
    check(
        "no turn started after the settings save",
        len(after) == before and entry["state"] == "queued",
        f"runs {before}->{len(after)}, entry {entry['state']}",
    )

    status, queue = e2e.request("GET", f"/projects/{project}/queue/{agent}/status")
    reason = (queue or {}).get("waiting_reason") or ""
    check("the queue says it waits for Continue", "Continue" in reason, repr(reason))

    status, res = e2e.request("POST", f"/projects/{project}/conversations/{successor}/continue")
    check(
        "Continue starts the successor",
        status == 200 and res.get("started") is True,
        f"{status} {res}",
    )
    deadline = time.time() + 60
    while time.time() < deadline and checkpoint_entry(project, agent, entry_id=mine)["state"] == "queued":
        time.sleep(3)
    check("the checkpoint entry was delivered", checkpoint_entry(project, agent, entry_id=mine)["state"] == "delivered")
    latest = alpha_runs(project, agent)[-1]
    e2e.wait_for(latest["id"], 5)


if __name__ == "__main__":
    try:
        main(*sys.argv[1:])
    finally:
        # Stop the chain whatever happened, so a failing drive does not keep spending.
        save_settings(sys.argv[1], checkpoint_mode="off")
        print("FAILED: " + ", ".join(failures) if failures else "ALL PASS")
    sys.exit(1 if failures else 0)
