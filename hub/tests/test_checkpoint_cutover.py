"""Handing a conversation over to its successor.

Tasks 8.1-8.3 and 8.10 of 2026-08-07-conversation-handoff-rework.

A cutover is three things that must happen together or not at all: a successor exists, it has the
checkpoint, and the predecessor is closed. Doing the third without the second strands the work;
doing the second without the third leaves two open conversations both looking current.
"""

