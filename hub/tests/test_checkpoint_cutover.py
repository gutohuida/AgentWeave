@pytest.mark.asyncio
async def test_cutover_creates_a_successor_delivers_and_archives(app):
    async with async_session_factory() as db:
        conversation = await _conversation(db, runtime_overrides={"permission_mode": "manual"})
        checkpoint = await _ready_checkpoint(db, conversation)

        successor, entry_id = await cut_over(db, conversation, checkpoint)

        entry = (
            await db.execute(select(InboundQueueEntry).where(InboundQueueEntry.id == entry_id))
        ).scalars().one()
        predecessor = await db.get(Conversation, "conv-1")

    assert successor.origin == "handoff"
    assert successor.title == "Continued: Wire up the worker"
    assert successor.lifecycle == "open"
    # The successor inherits what was in force. An inherited {"permission_mode": "manual"} is
    # what failed run-9058966b; dropping it at the boundary would change behaviour with nothing
    # on screen explaining why.
    assert successor.runtime_overrides == {"permission_mode": "manual"}

    # Conversation-scoped delivery, which `_render_hub_agent_context` cannot do — it writes one
    # file per agent, so three concurrent conversations would share one checkpoint.
    assert entry.conversation_id == successor.id
    assert entry.state == "queued"
    assert entry.origin_type == "checkpoint"
    assert entry.origin_agent is None

    assert predecessor.lifecycle == "archived"


