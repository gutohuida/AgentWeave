async def _conversation(db, conversation_id="conv-1", **overrides):
    fields = {
        "id": conversation_id,
        "project_id": PROJECT,
        "agent": AGENT,
        "lifecycle": "open",
        "origin": "operator",
        "title": "Wire up the worker",
        # `new_conversation` sets this to the row's own id; this fixture constructs the model
        # directly, so it has to do the same or every row here looks like a pre-migration row
        # with no lineage of its own.
        "lineage_id": conversation_id,
    }
    fields.update(overrides)
    conversation = Conversation(**fields)
    db.add(conversation)
    await db.commit()
    return conversation


async def _ready_checkpoint(db, conversation):
    return await create_checkpoint(
        db,
        conversation,
        trigger="context_pressure",
        envelope=await compute_envelope(db, conversation),
        body=render_body(CheckpointBody(**GOOD_BODY), notes_incorporated=False),
    )


