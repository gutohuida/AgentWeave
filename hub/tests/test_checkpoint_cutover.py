@pytest.mark.asyncio
async def test_a_running_conversation_is_not_cut_over(app):
    """Archiving would have to stop a live run, which destroys work with no undo."""
    async with async_session_factory() as db:
        conversation = await _conversation(db)
        checkpoint = await _ready_checkpoint(db, conversation)
        db.add(
            Run(
                id="run-live",
                project_id=PROJECT,
                agent=AGENT,
                conversation_id="conv-1",
                status="running",
            )
        )
        await db.commit()

        with pytest.raises(CutoverRefusedError, match="run in progress"):
            await cut_over(db, conversation, checkpoint)

        predecessor = await db.get(Conversation, "conv-1")

    # Refused means untouched, not half-done.
    assert predecessor.lifecycle == "open"


