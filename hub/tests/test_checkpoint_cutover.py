async def _configured_project(db, **overrides):
    fields = {
        "checkpoint_mode": "automatic",
        "checkpoint_threshold_mode": "percent",
        "checkpoint_threshold_value": 80,
        "checkpoint_notes_value": 70,
        "checkpoint_runner_id": "runner-1",
        "checkpoint_model": "claude-haiku-4-5-20251001",
    }
    fields.update(overrides)
    project = await db.get(Project, PROJECT)
    if project is None:
        project = Project(id=PROJECT, name="Testbed")
        db.add(project)
    for key, value in fields.items():
        setattr(project, key, value)
    if await db.get(Runner, "runner-1") is None:
        db.add(
            Runner(
                id="runner-1",
                project_id=PROJECT,
                name="Cheap",
                cli="claude",
                model="claude-haiku-4-5-20251001",
            )
        )
    db.add(Agent(id="agent-1", project_id=PROJECT, name=AGENT))
    await db.commit()
    return project


